    for relationship in relationships:

        if not validate_id_relationship(*relationship):
            failures += 1

    # --------------------------------------------------------
    # Business consistency
    # --------------------------------------------------------

    print("\n7. Business consistency validation")

    customer_account = (
        customers[
            [
                "customer_id",
                "account_id",
            ]
        ]
        .drop_duplicates()
    )

    sales_customer_check = sales.merge(
        customer_account,
        on="customer_id",
        how="left",
        suffixes=(
            "_sales",
            "_customer",
        ),
    )

    account_mismatch = (
        sales_customer_check["account_id_sales"]
        != sales_customer_check["account_id_customer"]
    ).sum()

    if not check(
        account_mismatch == 0,
        "Sales account matches customer account",
        f"Sales contains {account_mismatch:,} "
        "customer/account mismatches",
    ):
        failures += 1

    # --------------------------------------------------------
    # Machine → Location
    # --------------------------------------------------------

    machine_location = (
        machines[
            [
                "machine_id",
                "location_id",
            ]
        ]
        .drop_duplicates()
    )

    production_machine_check = production.merge(
        machine_location,
        on="machine_id",
        how="left",
        suffixes=(
            "_production",
            "_machine",
        ),
    )

    production_location_mismatch = (
        production_machine_check["location_id_production"]
        != production_machine_check["location_id_machine"]
    ).sum()

    if not check(
        production_location_mismatch == 0,
        "Production machine location matches machine master",
        f"Production contains {production_location_mismatch:,} "
        "machine/location mismatches",
    ):
        failures += 1

    maintenance_machine_check = maintenance.merge(
        machine_location,
        on="machine_id",
        how="left",
        suffixes=(
            "_maintenance",
            "_machine",
        ),
    )

    maintenance_location_mismatch = (
        maintenance_machine_check["location_id_maintenance"]
        != maintenance_machine_check["location_id_machine"]
    ).sum()

    if not check(
        maintenance_location_mismatch == 0,
        "Maintenance machine location matches machine master",
        f"Maintenance contains {maintenance_location_mismatch:,} "
        "machine/location mismatches",
    ):
        failures += 1

    # --------------------------------------------------------
    # Employee → Location
    # --------------------------------------------------------

    employee_location = (
        employees[
            [
                "employee_id",
                "location_id",
            ]
        ]
        .drop_duplicates()
    )

    production_employee_check = production.merge(
        employee_location,
        on="employee_id",
        how="left",
        suffixes=(
            "_production",
            "_employee",
        ),
    )

    employee_location_mismatch = (
        production_employee_check["location_id_production"]
        != production_employee_check["location_id_employee"]
    ).sum()

    if not check(
        employee_location_mismatch == 0,
        "Production employee location matches employee master",
        f"Production contains {employee_location_mismatch:,} "
        "employee/location mismatches",
    ):
        failures += 1

    # --------------------------------------------------------
    # Numeric business rules
    # --------------------------------------------------------

    print("\n8. Numeric business-rule validation")

    sales_revenue = (
        sales["quantity"]
        * sales["unit_price"]
        - sales["discount_amount"]
    )

    revenue_difference = np.abs(
        sales_revenue
        - sales["revenue"]
    )

    revenue_mismatch = (
        revenue_difference > 0.01
    ).sum()

    if not check(
        revenue_mismatch == 0,
        "Sales revenue calculation is consistent",
        f"Sales contains {revenue_mismatch:,} "
        "revenue calculation mismatches",
    ):
        failures += 1

    if not check(
        (sales["quantity"] > 0).all(),
        "Sales quantities are positive",
        "Sales contains non-positive quantities",
    ):
        failures += 1

    if not check(
        (sales["unit_price"] > 0).all(),
        "Sales unit prices are positive",
        "Sales contains non-positive unit prices",
    ):
        failures += 1

    if not check(
        (production["planned_quantity"] >= 0).all(),
        "Production planned quantities are non-negative",
        "Production contains negative planned quantities",
    ):
        failures += 1

    if not check(
        (production["produced_quantity"] >= 0).all(),
        "Production quantities are non-negative",
        "Production contains negative produced quantities",
    ):
        failures += 1

    if not check(
        (
            production["defect_quantity"]
            <= production["produced_quantity"]
        ).all(),
        "Production defect quantity does not exceed production quantity",
        "Production contains invalid defect quantities",
    ):
        failures += 1

    if not check(
        (maintenance["maintenance_hours"] > 0).all(),
        "Maintenance hours are positive",
        "Maintenance contains non-positive maintenance hours",
    ):
        failures += 1

    if not check(
        (maintenance["downtime_hours"] >= 0).all(),
        "Maintenance downtime is non-negative",
        "Maintenance contains negative downtime",
    ):
        failures += 1

    # --------------------------------------------------------
    # Inventory grain
    # --------------------------------------------------------

    print("\n9. Inventory grain validation")

    inventory_duplicates = inventory.duplicated(
        subset=[
            "product_id",
            "location_id",
            "inventory_date",
        ]
    ).sum()

    if not check(
        inventory_duplicates == 0,
        "Inventory grain Date + Product + Location is unique",
        f"Inventory contains {inventory_duplicates:,} "
        "duplicate grain combinations",
    ):
        failures += 1

    inventory_calculated = (
        inventory["opening_quantity"]
        + inventory["received_quantity"]
        - inventory["issued_quantity"]
    )

    inventory_mismatch = (
        inventory_calculated
        != inventory["closing_quantity"]
    ).sum()

    if not check(
        inventory_mismatch == 0,
        "Inventory closing quantity reconciles",
        f"Inventory contains {inventory_mismatch:,} "
        "quantity reconciliation errors",
    ):
        failures += 1

    if not check(
        (inventory["closing_quantity"] >= 0).all(),
        "Inventory closing quantity is non-negative",
        "Inventory contains negative closing quantities",
    ):
        failures += 1

    # --------------------------------------------------------
    # Date validation
    # --------------------------------------------------------

    print("\n10. Date-range validation")

    date_columns = {
        "sales.csv": "transaction_date",
        "production.csv": "production_date",
        "maintenance.csv": "maintenance_date",
        "financial_transactions.csv": "transaction_date",
        "budget.csv": "budget_date",
        "energy.csv": "measurement_date",
        "emissions.csv": "emissions_date",
        "waste.csv": "waste_date",
        "inventory.csv": "inventory_date",
    }

    start_date = pd.Timestamp("2019-01-01")
    end_date = pd.Timestamp("2025-12-31")

    for filename, column in date_columns.items():

        dates = pd.to_datetime(
            datasets[filename][column]
        )

        invalid_dates = (
            (dates < start_date)
            | (dates > end_date)
        ).sum()

        if not check(
            invalid_dates == 0,
            f"{filename}: dates fall within approved range",
            f"{filename}: {invalid_dates:,} dates outside approved range",
        ):
            failures += 1

    # --------------------------------------------------------
    # Final result
    # --------------------------------------------------------

    print("\n" + "=" * 60)

    if failures == 0:

        print("BUSINESS DATA VALIDATION PASSED")
        print("The nine clean business datasets are ready.")
        print("=" * 60)

        return True

    print(
        f"BUSINESS DATA VALIDATION FAILED "
        f"WITH {failures} FAILURE(S)"
    )

    print("=" * 60)

    return False



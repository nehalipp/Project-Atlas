def validate_final_data():

    print("=" * 60)
    print("Project Atlas — Final Raw Data Validation")
    print("Mode: QUALITY-ISSUE VALIDATION")
    print("=" * 60)

    print(
        "\nThe final raw layer is expected to contain "
        "controlled quality issues."
    )

    print(
        "This validation confirms the files exist, remain "
        "structurally usable, and contain the expected "
        "controlled defects."
    )

    datasets = {}

    for filename in EXPECTED_COUNTS:

        try:
            datasets[filename] = load_dataset(filename)

        except FileNotFoundError as error:
            print(f"FAIL  {error}")
            return False

    print("\n1. Record counts after quality injection")

    for filename, expected in EXPECTED_COUNTS.items():

        actual = len(datasets[filename])

        print(
            f"INFO  {filename}: "
            f"{actual:,} records"
        )

    print("\n2. Structural validation")

    failures = 0

    for filename, required in REQUIRED_COLUMNS.items():

        missing = (
            set(required)
            - set(datasets[filename].columns)
        )

        if not check(
            not missing,
            f"{filename}: required structure preserved",
            f"{filename}: missing columns {sorted(missing)}",
        ):
            failures += 1

    print("\n3. Expected quality issues")

    issue_summary = {}

    for filename, df in datasets.items():

        null_count = int(
            df.isna().sum().sum()
        )

        duplicate_rows = int(
            df.duplicated().sum()
        )

        issue_summary[filename] = {
            "null_cells": null_count,
            "duplicate_rows": duplicate_rows,
        }

        print(
            f"INFO  {filename}: "
            f"{null_count:,} null cells, "
            f"{duplicate_rows:,} duplicate rows"
        )

    total_nulls = sum(
        item["null_cells"]
        for item in issue_summary.values()
    )

    total_duplicates = sum(
        item["duplicate_rows"]
        for item in issue_summary.values()
    )

    if not check(
        total_nulls > 0,
        "Controlled missing values detected",
        "No missing values detected after quality injection",
    ):
        failures += 1

    if not check(
        total_duplicates > 0,
        "Controlled duplicate records detected",
        "No duplicate records detected after quality injection",
    ):
        failures += 1

    print("\n4. Final raw-data assessment")

    if failures == 0:

        print(
            "PASS  Final raw datasets contain the "
            "expected controlled quality issues."
        )

        print(
            "PASS  Final raw datasets remain structurally usable."
        )

        print("\n" + "=" * 60)
        print("FINAL RAW DATA VALIDATION PASSED")
        print("=" * 60)

        return True

    print("\n" + "=" * 60)
    print(
        f"FINAL RAW DATA VALIDATION FAILED "
        f"WITH {failures} FAILURE(S)"
    )
    print("=" * 60)

    return False


# ============================================================
# Main
# ============================================================

def main():

    final_mode = (
        len(sys.argv) > 1
        and sys.argv[1].lower() == "--final"
    )

    if final_mode:
        success = validate_final_data()
    else:
        success = validate_clean_data()

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()

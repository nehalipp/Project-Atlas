def load_dataset(filename):
    path = RAW_DATA_DIR / filename

    if not path.exists():
        raise FileNotFoundError(
            f"Required file not found: {path}"
        )

    return pd.read_csv(path)


def load_reference_data():
    files = [
        "accounts.csv",
        "customers.csv",
        "products.csv",
        "locations.csv",
        "employees.csv",
        "machines.csv",
    ]

    return {
        filename: load_dataset(filename)
        for filename in files
    }


def check(condition, passed_message, failed_message):
    if condition:
        print(f"PASS  {passed_message}")
        return True

    print(f"FAIL  {failed_message}")
    return False


def validate_id_relationship(
    child_df,
    child_column,
    parent_df,
    parent_column,
    relationship_name,
):
    child_values = set(
        child_df[child_column]
        .dropna()
        .astype(str)
    )

    parent_values = set(
        parent_df[parent_column]
        .dropna()
        .astype(str)
    )

    invalid = child_values - parent_values

    if not invalid:
        print(
            f"PASS  {relationship_name}"
        )
        return True

    print(
        f"FAIL  {relationship_name}: "
        f"{len(invalid):,} invalid references"
    )

    return False



def validate_clean_data():

    failures = 0

    print("=" * 60)
    print("Project Atlas — Business Data Validation")
    print("Mode: CLEAN BASELINE")
    print("=" * 60)

    print("\n1. Loading datasets")

    datasets = {}

    for filename in EXPECTED_COUNTS:

        try:
            datasets[filename] = load_dataset(filename)

            print(
                f"Loaded {filename}: "
                f"{len(datasets[filename]):,} records"
            )

        except FileNotFoundError as error:
            print(f"FAIL  {error}")
            failures += 1

    if failures:
        return False

    reference = load_reference_data()

    # --------------------------------------------------------
    # Record counts
    # --------------------------------------------------------

    print("\n2. Record count validation")

    for filename, expected in EXPECTED_COUNTS.items():

        actual = len(datasets[filename])

        if not check(
            actual == expected,
            f"{filename}: expected {expected:,}, found {actual:,}",
            f"{filename}: expected {expected:,}, found {actual:,}",
        ):
            failures += 1

    # --------------------------------------------------------
    # Required columns
    # --------------------------------------------------------

    print("\n3. Required column validation")

    for filename, required in REQUIRED_COLUMNS.items():

        actual_columns = set(
            datasets[filename].columns
        )

        missing = set(required) - actual_columns

        if not check(
            not missing,
            f"{filename}: all required columns present",
            f"{filename}: missing columns {sorted(missing)}",
        ):
            failures += 1

    # --------------------------------------------------------
    # Business-key uniqueness
    # --------------------------------------------------------

    print("\n4. Business-key uniqueness")

    id_columns = {
        "sales.csv": "transaction_id",
        "production.csv": "production_id",
        "maintenance.csv": "maintenance_id",
        "financial_transactions.csv":
            "financial_transaction_id",
        "budget.csv": "budget_id",
        "energy.csv": "energy_id",
        "emissions.csv": "emissions_id",
        "waste.csv": "waste_id",
        "inventory.csv": "inventory_id",
    }

    for filename, column in id_columns.items():

        df = datasets[filename]

        null_count = df[column].isna().sum()
        duplicate_count = df[column].duplicated().sum()

        if not check(
            null_count == 0,
            f"{filename}: {column} contains no nulls",
            f"{filename}: {column} contains {null_count:,} nulls",
        ):
            failures += 1

        if not check(
            duplicate_count == 0,
            f"{filename}: {column} contains no duplicates",
            f"{filename}: {column} contains {duplicate_count:,} duplicates",
        ):
            failures += 1

    # --------------------------------------------------------
    # Required fields
    # --------------------------------------------------------

    print("\n5. Required-field null validation")

    required_non_null = {
        "sales.csv": [
            "transaction_id",
            "transaction_date",
            "account_id",
            "customer_id",
            "product_id",
            "location_id",
        ],
        "production.csv": [
            "production_id",
            "production_date",
            "product_id",
            "location_id",
            "machine_id",
            "employee_id",
        ],
        "maintenance.csv": [
            "maintenance_id",
            "maintenance_date",
            "location_id",
            "machine_id",
            "employee_id",
        ],
        "financial_transactions.csv": [
            "financial_transaction_id",
            "transaction_date",
            "location_id",
            "category",
        ],
        "budget.csv": [
            "budget_id",
            "budget_date",
            "location_id",
            "budget_category",
        ],
        "energy.csv": [
            "energy_id",
            "measurement_date",
            "location_id",
            "energy_type",
        ],
        "emissions.csv": [
            "emissions_id",
            "emissions_date",
            "location_id",
            "emission_source",
        ],
        "waste.csv": [
            "waste_id",
            "waste_date",
            "location_id",
            "waste_type",
        ],
        "inventory.csv": [
            "inventory_id",
            "inventory_date",
            "product_id",
            "location_id",
        ],
    }

    for filename, columns in required_non_null.items():

        df = datasets[filename]

        for column in columns:

            null_count = df[column].isna().sum()

            if not check(
                null_count == 0,
                f"{filename}: {column} contains no nulls",
                f"{filename}: {column} contains {null_count:,} nulls",
            ):
                failures += 1

    # --------------------------------------------------------
    # Foreign-key validation
    # --------------------------------------------------------

    print("\n6. Foreign-key validation")

    accounts = reference["accounts.csv"]
    customers = reference["customers.csv"]
    products = reference["products.csv"]
    locations = reference["locations.csv"]
    employees = reference["employees.csv"]
    machines = reference["machines.csv"]

    sales = datasets["sales.csv"]
    production = datasets["production.csv"]
    maintenance = datasets["maintenance.csv"]
    financial = datasets["financial_transactions.csv"]
    budget = datasets["budget.csv"]
    energy = datasets["energy.csv"]
    emissions = datasets["emissions.csv"]
    waste = datasets["waste.csv"]
    inventory = datasets["inventory.csv"]

